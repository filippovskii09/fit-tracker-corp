import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(__dirname, '..');
const tokensPath = resolve(rootDir, 'tokens/design-tokens.json');
const cssPath = resolve(rootDir, 'src/styles/tokens.css');
const isCheck = process.argv.includes('--check');

const generatedHeader = '/* This file is generated by scripts/generate-design-tokens.mjs. Do not edit directly. */';

const tokens = JSON.parse(await readFile(tokensPath, 'utf8'));

const toThemeVariable = ([name, value], namespace) => `  --${namespace}-${name}: ${value};`;
const toRootVariable = ([name, value]) => `  --app-${name}: ${value};`;

const cssOutput = `${generatedHeader}

@theme {
${Object.entries(tokens.color).map((entry) => toThemeVariable(entry, 'color')).join('\n')}
${Object.entries(tokens.spacing).map((entry) => toThemeVariable(entry, 'spacing')).join('\n')}
${Object.entries(tokens.text).map((entry) => toThemeVariable(entry, 'text')).join('\n')}
${Object.entries(tokens.shadow).map((entry) => toThemeVariable(entry, 'shadow')).join('\n')}
}

:root {
${Object.entries(tokens.app).map(toRootVariable).join('\n')}
}
`;

const checkFile = async (path, expected) => {
  const current = await readFile(path, 'utf8');

  if (current !== expected) {
    throw new Error(`${path} is out of date. Run npm run tokens.`);
  }
};

if (isCheck) {
  await checkFile(cssPath, cssOutput);
} else {
  await writeFile(cssPath, cssOutput);
}
